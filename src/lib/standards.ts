export interface LevelRow { bw: number; levels: [number, number, number, number, number] } // bodyweight kg -> 1RM kg (or reps) at Beginner..Elite
export interface LiftStandard {
  key: string // short id, e.g. 'bench'
  name: string // display name, e.g. 'Bench press'
  match: RegExp // matches Hevy exercise names
  metric: 'kg' | 'reps'
  perDumbbell?: boolean
  url: string // the exact page the numbers came from
  male: LevelRow[]
  female: LevelRow[]
}
